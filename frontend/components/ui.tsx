"use client";

import type { ReactNode } from "react";

import { errorText } from "@/lib/api";
import { displayValue } from "@/lib/format";
import type { JobStatus, ReviewStatus } from "@/lib/types";

export function Panel({ title, action, children, className = "" }: { title?: ReactNode; action?: ReactNode; children: ReactNode; className?: string }) {
  return (
    <section className={`rounded-md border border-line bg-panel ${className}`}>
      {(title || action) && (
        <header className="flex flex-wrap items-center justify-between gap-2 border-b border-line px-4 py-2.5">
          <h2 className="text-[15px] font-semibold">{title}</h2>
          {action}
        </header>
      )}
      <div className="p-4">{children}</div>
    </section>
  );
}

export function PageHeader({ title, subtitle, actions }: { title: string; subtitle?: ReactNode; actions?: ReactNode }) {
  return (
    <div className="mb-5 flex flex-wrap items-end justify-between gap-3">
      <div className="max-w-3xl">
        <h1 className="text-2xl font-semibold">{title}</h1>
        {subtitle && <p className="mt-1 text-muted">{subtitle}</p>}
      </div>
      {actions}
    </div>
  );
}

type Tone = "neutral" | "accent" | "risk" | "ok" | "danger" | "synthetic";
const TONES: Record<Tone, string> = {
  neutral: "border-line text-muted bg-panel-2",
  accent: "border-accent/40 text-accent bg-panel",
  risk: "border-risk/40 text-risk bg-risk-soft",
  ok: "border-ok/40 text-ok bg-ok-soft",
  danger: "border-danger/40 text-danger bg-danger-soft",
  synthetic: "border-synthetic/40 text-synthetic bg-synthetic-soft",
};

export function Pill({ tone = "neutral", children, title }: { tone?: Tone; children: ReactNode; title?: string }) {
  return (
    <span title={title} className={`inline-flex items-center whitespace-nowrap rounded-full border px-2 py-0.5 text-[11px] font-medium uppercase tracking-wide ${TONES[tone]}`}>
      {children}
    </span>
  );
}

export function SyntheticBadge({ synthetic }: { synthetic: boolean }) {
  return synthetic ? (
    <Pill tone="synthetic" title="Generated by TransactionGuard's synthetic generator. Not real transactions; not benchmark evidence.">
      Synthetic
    </Pill>
  ) : (
    <Pill tone="neutral" title="Public ULB/OpenML benchmark: real, PCA-anonymized transactions.">
      Benchmark
    </Pill>
  );
}

export function FlagPill({ flagged }: { flagged: boolean }) {
  return flagged ? <Pill tone="risk">Review</Pill> : <Pill>No action</Pill>;
}

export function ReviewPill({ status }: { status: ReviewStatus | null | undefined }) {
  if (!status) return <span className="text-muted">-</span>;
  const tone: Tone = status === "resolved" ? "ok" : status === "under_review" ? "accent" : "risk";
  return <Pill tone={tone}>{status.replace("_", " ")}</Pill>;
}

export function JobPill({ status }: { status: JobStatus }) {
  const tone: Tone = status === "succeeded" ? "ok" : status === "failed" ? "danger" : "accent";
  return <Pill tone={tone}>{status}</Pill>;
}

export function Loading({ label = "Loading" }: { label?: string }) {
  return (
    <div role="status" className="flex items-center gap-2 py-6 text-muted">
      <span className="h-3 w-3 animate-pulse rounded-full bg-accent" />
      {label}…
    </div>
  );
}

export function ErrorState({ error, retry }: { error: unknown; retry?: () => void }) {
  return (
    <div role="alert" className="rounded-md border border-danger/40 bg-danger-soft px-4 py-3 text-danger">
      <p>{errorText(error)}</p>
      {retry && (
        <button type="button" onClick={retry} className="mt-2 text-sm font-medium underline">
          Try again
        </button>
      )}
    </div>
  );
}

export function EmptyState({ title, children }: { title: string; children?: ReactNode }) {
  return (
    <div className="rounded-md border border-dashed border-line px-4 py-8 text-center">
      <p className="font-medium">{title}</p>
      {children && <div className="mt-1 text-muted">{children}</div>}
    </div>
  );
}

export function Button({
  children,
  variant = "primary",
  ...props
}: React.ButtonHTMLAttributes<HTMLButtonElement> & { variant?: "primary" | "secondary" | "ghost" }) {
  const styles = {
    primary: "bg-accent text-accent-ink hover:opacity-90",
    secondary: "border border-line bg-panel hover:bg-panel-2",
    ghost: "text-accent hover:underline",
  }[variant];
  return (
    <button
      type="button"
      {...props}
      className={`inline-flex items-center justify-center gap-1.5 rounded-md px-3 py-1.5 text-sm font-medium disabled:cursor-not-allowed disabled:opacity-50 ${styles} ${props.className ?? ""}`}
    >
      {children}
    </button>
  );
}

export const inputClass =
  "w-full rounded-md border border-line bg-panel px-2.5 py-1.5 text-sm text-ink placeholder:text-muted/70 focus:border-accent";

export function Label({ htmlFor, children, hint }: { htmlFor: string; children: ReactNode; hint?: string }) {
  return (
    <label htmlFor={htmlFor} className="mb-1 block text-xs font-medium text-muted">
      {children}
      {hint && <span className="ml-1 font-normal opacity-80">({hint})</span>}
    </label>
  );
}

export function Stat({ label, value, hint, tone }: { label: string; value: ReactNode; hint?: ReactNode; tone?: "risk" | "danger" }) {
  return (
    <div className="rounded-md border border-line bg-panel px-4 py-3">
      <div className="text-xs uppercase tracking-wide text-muted">{label}</div>
      <div className={`num mt-1 text-2xl ${tone === "risk" ? "text-risk" : tone === "danger" ? "text-danger" : ""}`}>{value}</div>
      {hint && <div className="mt-0.5 text-xs text-muted">{hint}</div>}
    </div>
  );
}

export function Pagination({ page, pageSize, total, onPage }: { page: number; pageSize: number; total: number; onPage: (p: number) => void }) {
  const pages = Math.max(1, Math.ceil(total / pageSize));
  return (
    <div className="mt-3 flex items-center justify-between text-sm text-muted">
      <span className="num">
        {total === 0 ? 0 : (page - 1) * pageSize + 1}–{Math.min(page * pageSize, total)} of {total.toLocaleString()}
      </span>
      <div className="flex gap-2">
        <Button variant="secondary" disabled={page <= 1} onClick={() => onPage(page - 1)}>
          Previous
        </Button>
        <Button variant="secondary" disabled={page >= pages} onClick={() => onPage(page + 1)}>
          Next
        </Button>
      </div>
    </div>
  );
}

export function KeyValues({ data }: { data: Record<string, unknown> }) {
  return (
    <dl className="grid grid-cols-[minmax(8rem,auto)_1fr] gap-x-4 gap-y-1.5 text-sm">
      {Object.entries(data).map(([k, v]) => (
        <div key={k} className="contents">
          <dt className="text-muted">{k}</dt>
          <dd className="num break-all">{v === null || v === undefined ? <span className="text-muted">missing</span> : typeof v === "object" ? JSON.stringify(v) : displayValue(v)}</dd>
        </div>
      ))}
    </dl>
  );
}
